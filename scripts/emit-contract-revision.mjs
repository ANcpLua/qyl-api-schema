/**
 * Emits the contract revision into both generated faces of the contract.
 *
 * The revision is a content hash of the emitted OpenAPI document, so it is a
 * property of the contract itself: two builds of the same TypeSpec agree on it
 * whatever their package versions say, and no contract edit can reach a client
 * without changing it. Package versions cannot do that job — they move for
 * release reasons and stand still for contract ones.
 *
 * It runs after the OpenAPI emit rather than inside an emitter because no
 * emitter can hash a file its own compile pass is still writing.
 *
 *   node scripts/emit-contract-revision.mjs            both faces
 *   node scripts/emit-contract-revision.mjs --csharp   C# only (NuGet packing)
 *   node scripts/emit-contract-revision.mjs --ts       TypeScript only
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const openApiPath = "generated/openapi/qyl.openapi.json";
const csharpPath = "generated/contracts/Qyl/Api/ContractRevision.cs";
const tsPath = "generated/ts-types/api.ts";

// Everything from this line to the end of api.ts belongs to this script; the
// TypeSpec emitter owns everything above it. Re-running rewrites the block
// instead of stacking a second one.
const tsMarker = "// --- contract revision (scripts/emit-contract-revision.mjs) ---";

const flags = process.argv.slice(2);
const unknown = flags.filter((flag) => flag !== "--csharp" && flag !== "--ts");
if (unknown.length > 0) {
  throw new Error(`emit-contract-revision: unknown argument(s) ${unknown.join(", ")}`);
}
const emitCSharp = flags.length === 0 || flags.includes("--csharp");
const emitTs = flags.length === 0 || flags.includes("--ts");

let openApi;
try {
  openApi = await readFile(openApiPath);
} catch {
  throw new Error(
    `emit-contract-revision: '${openApiPath}' is missing — run \`npm run compile\` so the OpenAPI emit precedes the revision.`,
  );
}

const revision = `sha256:${createHash("sha256").update(openApi).digest("hex").slice(0, 16)}`;

if (emitCSharp) {
  await mkdir(dirname(csharpPath), { recursive: true });
  await writeFile(
    csharpPath,
    `﻿// <auto-generated/>
// Copyright (c) 2025-2026 ancplua
#nullable enable

namespace Qyl.Api.Contracts;

/// <summary>
/// The revision of the API contract these generated types were emitted from.
/// </summary>
public static class ContractRevision
{
    /// <summary>
    /// Matches <c>HealthReport.contract_revision</c> on a process serving this
    /// same contract. A client compares the two and refuses to run on a
    /// mismatch.
    /// </summary>
    public const string Value = "${revision}";
}
`,
  );
}

if (emitTs) {
  let api;
  try {
    api = await readFile(tsPath, "utf8");
  } catch {
    throw new Error(
      `emit-contract-revision: '${tsPath}' is missing — run \`npm run compile\` so the TypeScript emit precedes the revision.`,
    );
  }

  const markerIndex = api.indexOf(tsMarker);
  const emitted = markerIndex === -1 ? api : api.slice(0, markerIndex);
  await writeFile(
    tsPath,
    `${emitted.trimEnd()}\n\n${tsMarker}\n` +
      "/** Revision of the API contract these types were emitted from; compare against HealthReport.contract_revision. */\n" +
      `export const CONTRACT_REVISION: string = "${revision}";\n`,
  );
}

console.log(
  `emit-contract-revision: ${revision} -> ${
    [emitCSharp ? csharpPath : undefined, emitTs ? tsPath : undefined].filter(Boolean).join(", ")
  }`,
);
