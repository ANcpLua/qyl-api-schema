/**
 * Emits NativeAOT-safe, self-contained JSON Schemas for qyl's in-process named
 * MCP tools into the generated C# contract assembly.
 *
 * The TypeSpec JSON Schema bundle remains the only schema source. Each constant
 * contains the selected definition at the document root plus the minimal
 * transitive $defs closure needed to resolve its local references. Consumers
 * can parse and write the constant directly as an MCP inputSchema/outputSchema;
 * they do not reconstruct constraints from DTO reflection.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const input = "generated/json-schema/qyl-api-schema.json";
const output = "generated/contracts/Qyl/Api/Mcp/ToolSchemas.cs";
const definitions = [
  "Mcp.Tools.GetActiveWorkflowRunInput",
  "Mcp.Tools.GetActiveWorkflowRunOutput",
  "Mcp.Tools.RecordDiagnosticSnapshotInput",
  "Mcp.Tools.RecordDiagnosticSnapshotOutput",
];

const bundle = JSON.parse(await readFile(input, "utf8"));
const allDefinitions = bundle.$defs ?? {};
const compareNames = (left, right) => left === right ? 0 : left < right ? -1 : 1;

function referencedDefinition(ref, owner) {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) {
    throw new Error(`emit-mcp-tool-schemas: ${owner} has unsupported non-local reference '${ref}'.`);
  }
  return ref.slice(prefix.length);
}

function collectReferences(value, owner, found) {
  if (Array.isArray(value)) {
    for (const child of value) collectReferences(child, owner, found);
    return;
  }
  if (value === null || typeof value !== "object") return;

  if (typeof value.$ref === "string") {
    const name = referencedDefinition(value.$ref, owner);
    if (!(name in allDefinitions)) {
      throw new Error(`emit-mcp-tool-schemas: ${owner} references missing definition '${name}'.`);
    }
    if (!found.has(name)) {
      found.add(name);
      collectReferences(allDefinitions[name], owner, found);
    }
  }
  for (const child of Object.values(value)) collectReferences(child, owner, found);
}

function standaloneSchema(name) {
  const definition = allDefinitions[name];
  if (!definition) throw new Error(`emit-mcp-tool-schemas: definition '${name}' is missing.`);

  const referenced = new Set();
  collectReferences(definition, name, referenced);
  const schema = {
    $schema: bundle.$schema,
    ...definition,
  };
  if (referenced.size > 0) {
    schema.$defs = Object.fromEntries(
      [...referenced]
        .sort(compareNames)
        .map((reference) => [reference, allDefinitions[reference]]),
    );
  }
  return JSON.stringify(schema);
}

function constantName(definition) {
  return definition.slice("Mcp.Tools.".length);
}

const constants = definitions.map((definition) => {
  const json = standaloneSchema(definition);
  if (json.includes('"""')) {
    throw new Error(`emit-mcp-tool-schemas: ${definition} cannot be represented by a C# raw string literal.`);
  }
  return `    public const string ${constantName(definition)} = """${json}""";`;
});

await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `﻿// <auto-generated/>
// Copyright (c) 2025-2026 ancplua
#nullable enable

namespace Qyl.Api.Contracts.Mcp;

/// <summary>
/// Canonical standalone JSON Schemas for qyl's in-process named MCP tools.
/// </summary>
public static class ToolSchemas
{
${constants.join("\n")}
}
`,
);

console.log(`emit-mcp-tool-schemas: ${definitions.length} schema(s) -> ${output}`);
